using Simple.OData.Client.Tests.Infrastructure;

namespace Simple.OData.Client.Tests.Server;

public sealed class InsertTypedTests(TestServerFixture fixture) : ServerTestBase(fixture)
{
	[Fact]
	public async Task Insert()
	{
		var product = await CreateClient().For<Product>().Set(new { ProductName = "Test1", UnitPrice = 18m }).InsertEntryAsync();
		product!.ProductName.Should().Be("Test1");
	}

	[Fact]
	public async Task InsertAutogeneratedID()
	{
		var product = await CreateClient().For<Product>().Set(new { ProductName = "Test1", UnitPrice = 18m }).InsertEntryAsync();
		product!.ProductID.Should().BeGreaterThan(Seed.Products);
		product.ProductName.Should().Be("Test1");
	}

	[Fact]
	public async Task InsertWithSelect()
	{
		var product = await CreateClient().For<Product>().Set(new { ProductName = "Test1", UnitPrice = 18m }).Select(x => new { x.ProductID }).InsertEntryAsync();
		product!.ProductID.Should().NotBe(0);
		product.ProductName.Should().BeNull();
		product.UnitPrice.Should().Be(0);
	}

	[Fact]
	public async Task InsertWithMappedColumn()
	{
		var product = await CreateClient().For<Product>().Set(new Product { ProductName = "Test1", UnitPrice = 18m, MappedEnglishName = "EnglishTest" }).InsertEntryAsync();
		product!.ProductName.Should().Be("Test1");
		product.MappedEnglishName.Should().Be("EnglishTest");
	}

	[Fact]
	public async Task InsertProductWithCategoryByID()
	{
		var client = CreateClient();
		var category = await client.For<Category>().Set(new { CategoryName = "Test3" }).InsertEntryAsync();
		var product = await client.For<Product>().Set(new { ProductName = "Test4", UnitPrice = 18m, CategoryID = category!.CategoryID }).InsertEntryAsync();
		product!.ProductName.Should().Be("Test4");
		product.CategoryID.Should().Be(category.CategoryID);
		category = await client.For<Category>().Expand(x => new { x.Products }).Filter(x => x.CategoryName == "Test3").FindEntryAsync();
		category!.Products.Should().ContainSingle();
	}

	[Fact]
	public async Task InsertProductWithCategoryByAssociation()
	{
		var client = CreateClient();
		var category = await client.For<Category>().Set(new { CategoryName = "Test5" }).InsertEntryAsync();
		var product = await client.For<Product>().Set(new { ProductName = "Test6", UnitPrice = 18m, Category = category }).InsertEntryAsync();
		product!.ProductName.Should().Be("Test6");
		product.CategoryID.Should().Be(category!.CategoryID);
		category = await client.For<Category>().Expand(x => new { x.Products }).Filter(x => x.CategoryName == "Test5").FindEntryAsync();
		category!.Products.Should().ContainSingle();
	}

	[Fact]
	public async Task InsertCategoryWithPictureAsBytes()
	{
		var client = CreateClient();
		await client.For<Category>().Set(new { CategoryName = "Test7", Picture = new byte[] { 1, 2, 3, 4, 5 } }).InsertEntryAsync();
		var category = await client.For<Category>().Filter(x => x.CategoryName == "Test7").FindEntryAsync();
		category!.Picture.Should().Equal(1, 2, 3, 4, 5);
	}

	[Fact]
	public async Task InsertCategoryWithPictureAsString()
	{
		var client = CreateClient();
		await client.For<Category>().Set(new { CategoryName = "Test8", Picture = Convert.ToBase64String([1, 2, 3, 4, 5]) }).InsertEntryAsync();
		var category = await client.For<Category>().Filter(x => x.CategoryName == "Test8").FindEntryAsync();
		category!.Picture.Should().Equal(1, 2, 3, 4, 5);
	}

	[Fact]
	public async Task InsertShip()
	{
		var ship = await CreateClient().For<Transport>().As<Ship>().Set(new Ship { ShipName = "Test1" }).InsertEntryAsync();
		ship!.ShipName.Should().Be("Test1");
	}

	[Fact]
	public async Task InsertCustomerWithComplexAddressAndEnum()
	{
		var client = CreateClient();
		var customer = await client.For<Customer>()
			.Set(new Customer { CustomerID = "TYPED", CompanyName = "Typed Co", Address = new Address { City = "Bergen", Country = "Norway", Type = AddressType.Shipping } })
			.InsertEntryAsync();
		customer!.Address!.Type.Should().Be(AddressType.Shipping);
		var found = await client.For<Customer>().Key("TYPED").FindEntryAsync();
		found!.Address!.City.Should().Be("Bergen");
	}

	[Fact]
	public async Task InsertGuidKeyedEntry()
	{
		var client = CreateClient();
		var key = Guid.NewGuid();
		await client.For<TypeWithGuidKey>().Set(new TypeWithGuidKey { Key = key, Name = "third" }).InsertEntryAsync();
		(await client.For<TypeWithGuidKey>().Key(key).FindEntryAsync())!.Name.Should().Be("third");
	}
}
