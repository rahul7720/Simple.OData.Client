using System.Dynamic;
using Simple.OData.Client.Tests.Infrastructure;

namespace Simple.OData.Client.Tests.Server;

public sealed class InsertDynamicTests(TestServerFixture fixture) : ServerTestBase(fixture)
{
	[Fact]
	public async Task Insert()
	{
		var x = ODataDynamic.Expression;
		dynamic product = await CreateClient().For(x.Products).Set(x.ProductName = "Test1", x.UnitPrice = 18m).InsertEntryAsync();
		((string)product.ProductName).Should().Be("Test1");
	}

	[Fact]
	public async Task InsertAutogeneratedID()
	{
		var x = ODataDynamic.Expression;
		dynamic product = await CreateClient().For(x.Products).Set(x.ProductName = "Test1", x.UnitPrice = 18m).InsertEntryAsync();
		((int)product.ProductID).Should().BeGreaterThan(Seed.Products);
	}

	[Fact]
	public async Task InsertExpando()
	{
		var x = ODataDynamic.Expression;
		dynamic expando = new ExpandoObject();
		expando.ProductName = "Test9";
		expando.UnitPrice = 18m;
		dynamic product = await CreateClient().For(x.Products).Set(expando).InsertEntryAsync();
		((int)product.ProductID).Should().BeGreaterThan(0);
	}

	[Fact]
	public async Task InsertProductWithCategoryByID()
	{
		var x = ODataDynamic.Expression;
		var client = CreateClient();
		dynamic category = await client.For(x.Categories).Set(x.CategoryName = "Test3").InsertEntryAsync();
		dynamic product = await client.For(x.Products).Set(x.ProductName = "Test4", x.UnitPrice = 18m, x.CategoryID = category.CategoryID).InsertEntryAsync();
		((string)product.ProductName).Should().Be("Test4");
		((int)product.CategoryID).Should().Be((int)category.CategoryID);
		category = await client.For(x.Categories).Expand(x.Products).Filter(x.CategoryName == "Test3").FindEntryAsync();
		((IEnumerable<dynamic>)category.Products).Should().ContainSingle();
	}

	[Fact]
	public async Task InsertProductWithCategoryByAssociation()
	{
		var x = ODataDynamic.Expression;
		var client = CreateClient();
		dynamic category = await client.For(x.Categories).Set(x.CategoryName = "Test5").InsertEntryAsync();
		dynamic product = await client.For(x.Products).Set(x.ProductName = "Test6", x.UnitPrice = 18m, x.Category = category).InsertEntryAsync();
		((string)product.ProductName).Should().Be("Test6");
		((int)product.CategoryID).Should().Be((int)category.CategoryID);
		category = await client.For(x.Categories).Expand(x.Products).Filter(x.CategoryName == "Test5").FindEntryAsync();
		((IEnumerable<dynamic>)category.Products).Should().ContainSingle();
	}

	[Fact]
	public async Task InsertShip()
	{
		var x = ODataDynamic.Expression;
		dynamic ship = await CreateClient().For(x.Transport).As(x.Ship).Set(x.ShipName = "Test1").InsertEntryAsync();
		((string)ship.ShipName).Should().Be("Test1");
	}
}
