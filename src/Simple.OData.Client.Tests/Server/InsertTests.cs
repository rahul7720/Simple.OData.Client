using System.Dynamic;
using Simple.OData.Client.Tests.Infrastructure;
using Entry = System.Collections.Generic.Dictionary<string, object?>;

namespace Simple.OData.Client.Tests.Server;

public sealed class InsertTests(TestServerFixture fixture) : ServerTestBase(fixture)
{
	private static IReadOnlyList<IDictionary<string, object?>> Items(IDictionary<string, object?> entry, string key) =>
		((IEnumerable<object?>)entry[key]!).Cast<IDictionary<string, object?>>().ToList();

	[Fact]
	public async Task Insert()
	{
		var product = await CreateClient().For("Products").Set(new Entry { ["ProductName"] = "Test1", ["UnitPrice"] = 18m }).InsertEntryAsync();
		product!["ProductName"].Should().Be("Test1");
		product["UnitPrice"].Should().Be(18m);
	}

	[Fact]
	public async Task InsertWithValueConversion()
	{
		var product = await CreateClient().For("Products").Set(new Entry { ["ProductName"] = "Test1", ["UnitPrice"] = 18.0d }).InsertEntryAsync();
		product!["ProductName"].Should().Be("Test1");
		product["UnitPrice"].Should().Be(18m);
	}

	[Fact]
	public async Task InsertAutogeneratedID()
	{
		var product = await CreateClient().For("Products").Set(new { ProductName = "Test1", UnitPrice = 18m }).InsertEntryAsync();
		((int)product!["ProductID"]!).Should().BeGreaterThan(Seed.Products);
		product["ProductName"].Should().Be("Test1");
	}

	[Fact]
	public async Task InsertExpando()
	{
		dynamic expando = new ExpandoObject();
		expando.ProductName = "Test9";
		expando.UnitPrice = 18m;
		var product = await (Task<IDictionary<string, object?>?>)CreateClient().For("Products").Set(expando).InsertEntryAsync();
		((int)product!["ProductID"]!).Should().BeGreaterThan(0);
		product["ProductName"].Should().Be("Test9");
	}

	[Fact]
	public async Task InsertProductWithCategoryByID()
	{
		var client = CreateClient();
		var category = await client.For("Categories").Set(new { CategoryName = "Test3" }).InsertEntryAsync();
		var product = await client.For("Products").Set(new { ProductName = "Test4", UnitPrice = 18m, CategoryID = category!["CategoryID"] }).InsertEntryAsync();
		product!["ProductName"].Should().Be("Test4");
		product["CategoryID"].Should().Be(category["CategoryID"]);
		category = await client.For("Categories").Expand("Products").Filter("CategoryName eq 'Test3'").FindEntryAsync();
		Items(category!, "Products").Should().ContainSingle();
	}

	[Fact]
	public async Task InsertProductWithCategoryByAssociation()
	{
		var client = CreateClient();
		var category = await client.For("Categories").Set(new { CategoryName = "Test5" }).InsertEntryAsync();
		var product = await client.For("Products").Set(new { ProductName = "Test6", UnitPrice = 18m, Category = category }).InsertEntryAsync();
		product!["ProductName"].Should().Be("Test6");
		product["CategoryID"].Should().Be(category!["CategoryID"]);
		category = await client.For("Categories").Expand("Products").Filter("CategoryName eq 'Test5'").FindEntryAsync();
		Items(category!, "Products").Should().ContainSingle();
	}

	[Fact]
	public async Task InsertDeepCategoryWithProducts()
	{
		var client = CreateClient();
		var category = await client.For("Categories")
			.Set(new { CategoryName = "Deep", Products = new[] { new { ProductName = "Deep1", UnitPrice = 1m }, new { ProductName = "Deep2", UnitPrice = 2m } } })
			.InsertEntryAsync();
		category = await client.For("Categories").Key(category!["CategoryID"]).Expand("Products").FindEntryAsync();
		Items(category!, "Products").Select(x => x["ProductName"]).Should().BeEquivalentTo(["Deep1", "Deep2"]);
	}

	[Fact]
	public async Task InsertShip()
	{
		var ship = await CreateClient().For("Transport").As("Ship").Set(new { ShipName = "Test1" }).InsertEntryAsync();
		ship!["ShipName"].Should().Be("Test1");
		((int)ship["TransportID"]!).Should().BeGreaterThan(Seed.Transports);
	}

	[Fact]
	public async Task InsertCustomerWithComplexAddress()
	{
		var customer = await CreateClient().For("Customers")
			.Set(new Entry { ["CustomerID"] = "NEWCO", ["CompanyName"] = "New Co", ["Address"] = new Entry { ["City"] = "Oslo", ["Country"] = "Norway", ["Type"] = "Home" } })
			.InsertEntryAsync();
		((IDictionary<string, object?>)customer!["Address"]!)["City"].Should().Be("Oslo");
		var found = await CreateClient().For("Customers").Key("NEWCO").FindEntryAsync();
		((IDictionary<string, object?>)found!["Address"]!)["Country"].Should().Be("Norway");
	}

	[Fact]
	public async Task InsertOpenTypeWithDynamicProperties()
	{
		var animal = await CreateClient().For("Animals").Set(new Entry { ["Name"] = "Cat", ["Legs"] = 4, ["Indoor"] = true }).InsertEntryAsync();
		animal!["Legs"].Should().Be(4);
		var found = await CreateClient().For("Animals").Key(animal["Id"]).FindEntryAsync();
		found!["Indoor"].Should().Be(true);
	}

	[Fact]
	public async Task InsertReturnsEntryWithAnnotationsAndEtag()
	{
		var client = CreateClient(x => x.IncludeAnnotationsInResults = true);
		var product = await client.For("Products").Set(new { ProductName = "Annotated", UnitPrice = 1m }).InsertEntryAsync();
		var annotations = (ODataEntryAnnotations)product!["__annotations"]!;
		annotations.ETag.Should().StartWith("W/");
		annotations.Id.Should().Contain("Products(");
	}

	[Fact]
	public async Task InsertWithoutResult()
	{
		var client = CreateClient();
		var product = await client.For("Products").Set(new { ProductName = "Quiet", UnitPrice = 1m }).InsertEntryAsync(false);
		product.Should().BeNull();
		(await client.For("Products").Filter("ProductName eq 'Quiet'").FindEntriesAsync()).Should().ContainSingle();
	}
}
